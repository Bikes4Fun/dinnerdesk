"""Generate client/server filter catalogs. Run with --check in tests/CI.

The JSON is the only editable list. Generated native code needs no network or Python
at app startup and uses each platform's existing type system.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = "Generated by scripts/sync_filter_options.py; edit shared/filter-options.json."


class FilterCatalog:
    """Validate the shared choices and render the thin platform catalogs."""

    groups = ("diets", "allergens", "avoids", "who", "cuisines", "proteins", "times")

    def __init__(self, data: dict):
        self.data = data
        for group in self.groups:
            rows = data[group]
            if not rows or any(not isinstance(row, list) or len(row) != 2 or
                               any(not isinstance(v, str) or not v for v in row) for row in rows):
                raise ValueError(f"Invalid filter group: {group}")
            ids = self.ids(group)
            if len(ids) != len(set(ids)):
                raise ValueError(f"Duplicate filter ids: {group}")
        diets, proteins = set(self.ids("diets")), set(self.ids("proteins"))
        exclusive = data["exclusive_diets"]
        if len(exclusive) != len(set(exclusive)) or not set(exclusive) <= diets:
            raise ValueError("Invalid exclusive diets")
        if len(data["strictest"]) != len(exclusive) or set(data["strictest"]) != set(exclusive):
            raise ValueError("Strictest must order every exclusive diet once")
        for diet, allowed in data["protein_diets"].items():
            if diet not in diets or len(allowed) != len(set(allowed)) or not set(allowed) <= proteins:
                raise ValueError(f"Invalid protein diet: {diet}")

    def ids(self, group: str) -> list[str]:
        return [row[0] for row in self.data[group]]

    @staticmethod
    def string(value: str) -> str:
        return json.dumps(value, ensure_ascii=False)

    def strings(self, values: list[str]) -> str:
        return ", ".join(self.string(v) for v in values)

    def js(self) -> str:
        rows = [f"// {HEADER}"]
        for group in self.groups:
            value = self.ids(group) if group in ("diets", "avoids") else self.data[group]
            rows.append(f"export const {group.upper()} = {json.dumps(value, ensure_ascii=False)};")
        for key in ("exclusive_diets", "strictest", "protein_diets"):
            name = "EXCLUSIVE" if key == "exclusive_diets" else key.upper()
            rows.append(f"export const {name} = {json.dumps(self.data[key], ensure_ascii=False)};")
        rows.append(f"export const DIET_LABELS = {json.dumps(dict(self.data['diets']), ensure_ascii=False)};")
        rows.append("""
/** Reusable selection rules for Settings, the tour, and future filter editors. */
export class FilterOptions {
  static proteinsFor(diets) {
    const diet = STRICTEST.find(id => diets.includes(id));
    const allowed = PROTEIN_DIETS[diet];
    return allowed ? PROTEINS.filter(([id]) => allowed.includes(id)) : PROTEINS;
  }
}
""")
        return "\n".join(rows)

    def python(self) -> str:
        rows = [f'"""{HEADER}"""', ""]
        for group in self.groups:
            rows.append(f"{group.upper()} = {self.ids(group)!r}")
        rows.append(f"EXCLUSIVE_DIETS = {tuple(self.data['exclusive_diets'])!r}")
        rows.append(f"STRICTEST = {tuple(self.data['strictest'])!r}")
        return "\n".join(rows) + "\n"

    def swift(self) -> str:
        rows = [f"// {HEADER}", "import Foundation", "", "enum FilterOptions {"]
        for group in self.groups:
            if group in ("diets", "avoids"):
                rows.append(f"  static let {group} = [{self.strings(self.ids(group))}]")
            elif group == "times":
                rows.append("  struct TimeOption: Identifiable { let id: String; let label: String }")
                options = ", ".join(f"TimeOption(id: {self.string(k)}, label: {self.string(v)})" for k, v in self.data[group])
                rows.append(f"  static let times = [{options}]")
            else:
                options = ", ".join(f"({self.string(k)}, {self.string(v)})" for k, v in self.data[group])
                rows.append(f"  static let {group} = [{options}]")
        rows.append(f"  static let exclusiveDiets: Set<String> = [{self.strings(self.data['exclusive_diets'])}]")
        rows.append(f"  static let strictest = [{self.strings(self.data['strictest'])}]")
        labels = ", ".join(f"{self.string(k)}: {self.string(v)}" for k, v in self.data["diets"])
        rows.append(f"  static let dietLabels = [{labels}]")
        allowed = ", ".join(f"{self.string(k)}: [{self.strings(v)}]" for k, v in self.data["protein_diets"].items())
        rows.append(f"  static let proteinDiets: [String: Set<String>] = [{allowed}]")
        rows.append("""
  static func proteinsFor(_ diets: Set<String>) -> [(String, String)] {
    guard let diet = strictest.first(where: { diets.contains($0) }),
      let allowed = proteinDiets[diet] else { return proteins }
    return proteins.filter { allowed.contains($0.0) }
  }
}
""")
        return "\n".join(rows)

    def kotlin(self) -> str:
        rows = [f"// {HEADER}", "package build.computerscience.dinnerdesk.ui", "", "object FilterOptions {"]
        for group in self.groups:
            options = self.strings(self.ids(group)) if group in ("diets", "avoids") else ", ".join(
                f"{self.string(k)} to {self.string(v)}" for k, v in self.data[group])
            rows.append(f"    val {group} = listOf({options})")
        rows.append(f"    val exclusiveDiets = setOf({self.strings(self.data['exclusive_diets'])})")
        rows.append(f"    val strictest = listOf({self.strings(self.data['strictest'])})")
        labels = ", ".join(f"{self.string(k)} to {self.string(v)}" for k, v in self.data["diets"])
        rows.append(f"    val dietLabels = mapOf({labels})")
        allowed = ", ".join(f"{self.string(k)} to setOf({self.strings(v)})" for k, v in self.data["protein_diets"].items())
        rows.append(f"    val proteinDiets = mapOf({allowed})")
        rows.append("""
    fun proteinsFor(diets: Set<String>): List<Pair<String, String>> {
        val allowed = proteinDiets[strictest.firstOrNull { it in diets }] ?: return proteins
        return proteins.filter { it.first in allowed }
    }

    fun toggled(diets: Set<String>, item: String): Set<String> =
        if (item in exclusiveDiets) diets - exclusiveDiets + item else if (item in diets) diets - item else diets + item

    fun cleaned(saved: List<String>): Set<String> {
        val picked = strictest.firstOrNull { it in saved }
        return saved.toSet() - exclusiveDiets + listOfNotNull(picked)
    }
}
""")
        return "\n".join(rows)

    def taste_lab(self) -> str:
        rows = [f"  // {HEADER}"]
        for group in ("avoids", "allergens", "diets"):
            value = self.ids(group) if group == "avoids" else self.data[group]
            rows.append(f"  const {group.upper()} = {json.dumps(value, ensure_ascii=False)};")
        return "\n".join(rows) + "\n"

    def outputs(self, root: Path = ROOT) -> dict[Path, str]:
        lab_path = root / "tastelab/web/app.js"
        lab = lab_path.read_text(encoding="utf-8")
        marker = f"  // {HEADER}"
        start = lab.index(marker) if marker in lab else lab.index("  const AVOIDS =")
        end = lab.index("  const MIN_POOL", start)
        return {
            root / "web/src/filterOptions.js": self.js(),
            root / "app/domain/filter_options.py": self.python(),
            root / "ios/dinnerdesk/FilterOptions.swift": self.swift(),
            root / "android/app/src/main/java/build/computerscience/dinnerdesk/ui/FilterOptions.kt": self.kotlin(),
            lab_path: lab[:start] + self.taste_lab() + lab[end:],
        }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated definitions have drifted")
    args = parser.parse_args()
    catalog = FilterCatalog(json.loads((ROOT / "shared/filter-options.json").read_text(encoding="utf-8")))
    stale = []
    for path, expected in catalog.outputs().items():
        actual = path.read_text(encoding="utf-8") if path.exists() else None
        if actual == expected:
            continue
        if args.check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(expected, encoding="utf-8", newline="\n")
    if stale:
        print("Regenerate filter options: python scripts/sync_filter_options.py\n" + "\n".join(stale))
        return 1
    print("Filter options are in sync.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

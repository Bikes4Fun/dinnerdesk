"""Generate report models for every client and server; --check detects drift."""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = "Generated by scripts/sync_report_options.py; edit shared/report-options.json."


class ReportCatalog:
    """One report vocabulary, rendered into each platform's native model types."""

    names = {"recipe": "RecipeReportReason", "ingredient": "IngredientReportReason", "prep": "PrepReason"}

    def __init__(self, data: dict):
        if set(data) != set(self.names):
            raise ValueError("Expected recipe, ingredient and prep report groups")
        self.data = data
        for kind, choices in data.items():
            ids = []
            for choice in choices:
                if not isinstance(choice, list) or len(choice) != 2:
                    raise ValueError(f"Invalid report choice: {kind}")
                key, label = choice
                if not isinstance(key, str) or not re.fullmatch(r"[a-z]+(?:_[a-z]+)*", key) or not isinstance(label, str) or not label.strip():
                    raise ValueError(f"Invalid report choice: {kind}")
                ids.append(key)
            if not ids or len(ids) != len(set(ids)):
                raise ValueError(f"Empty or duplicate report ids: {kind}")

    @staticmethod
    def string(value: str) -> str:
        return json.dumps(value, ensure_ascii=False)

    @staticmethod
    def member(key: str) -> str:
        first, *rest = key.split("_")
        return first + "".join(word.title() for word in rest)

    def swift(self) -> str:
        blocks = [f"// {HEADER}", "import Foundation"]
        for kind, name in self.names.items():
            rows = [f"enum {name}: String, CaseIterable, Identifiable, Sendable {{"]
            for key, _ in self.data[kind]:
                rows.append(f"  case {self.member(key)} = {self.string(key)}")
            rows += ["  var id: String { rawValue }", "  var label: String {", "    switch self {"]
            for key, label in self.data[kind]:
                rows.append(f"    case .{self.member(key)}: return {self.string(label)}")
            rows += ["    }", "  }", "}"]
            blocks.append("\n".join(rows))
        return "\n\n".join(blocks) + "\n"

    def kotlin(self) -> str:
        blocks = [f"// {HEADER}", "package build.computerscience.dinnerdesk.data"]
        for kind, name in self.names.items():
            rows = [f"enum class {name}(val id: String, val label: String) {{"]
            for index, (key, label) in enumerate(self.data[kind]):
                member = self.member(key)
                ending = ";" if index == len(self.data[kind]) - 1 else ","
                rows.append(f"    {member[0].upper() + member[1:]}({self.string(key)}, {self.string(label)}){ending}")
            if kind == "prep":
                rows += ["", "    companion object {", "        fun of(id: String?) = entries.firstOrNull { it.id == id }", "    }"]
            rows.append("}")
            blocks.append("\n".join(rows))
        return "\n\n".join(blocks) + "\n"

    def python(self) -> str:
        return f'''"""{HEADER}"""


class ReportCatalog:
    _choices = {repr({kind: tuple(map(tuple, rows)) for kind, rows in self.data.items()})}

    @classmethod
    def choices(cls, kind: str) -> tuple[tuple[str, str], ...]:
        return cls._choices[kind]

    @classmethod
    def ids(cls, kind: str) -> tuple[str, ...]:
        return tuple(key for key, _ in cls.choices(kind))

    @classmethod
    def labels(cls, kind: str) -> dict[str, str]:
        return dict(cls.choices(kind))
'''

    def js(self) -> str:
        return f'''// {HEADER}
const choices = {json.dumps(self.data, ensure_ascii=False)};
for (const rows of Object.values(choices)) {{
  rows.forEach(Object.freeze);
  Object.freeze(rows);
}}

export class ReportCatalog {{
  static choices(kind) {{
    if (!Object.hasOwn(choices, kind)) throw new Error(`Unknown report kind: ${{kind}}`);
    return choices[kind];
  }}
  static labels(kind) {{ return Object.fromEntries(this.choices(kind)); }}
}}

export const REPORT_REASONS = ReportCatalog.choices("recipe");
export const INGREDIENT_REPORT_REASONS = ReportCatalog.choices("ingredient");
export const PREP_REASONS = ReportCatalog.choices("prep");
'''

    def outputs(self, root: Path = ROOT) -> dict[Path, str]:
        return {
            root / "app/domain/report_options.py": self.python(),
            root / "web/src/reportOptions.js": self.js(),
            root / "ios/dinnerdesk/ReportOptions.swift": self.swift(),
            root / "android/app/src/main/java/build/computerscience/dinnerdesk/data/ReportOptions.kt": self.kotlin(),
        }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    catalog = ReportCatalog(json.loads((ROOT / "shared/report-options.json").read_text(encoding="utf-8")))
    stale = []
    for path, expected in catalog.outputs().items():
        actual = path.read_text(encoding="utf-8") if path.exists() else None
        if actual == expected:
            continue
        if args.check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(expected, encoding="utf-8", newline="\n")
    if stale:
        print("Regenerate report options: python scripts/sync_report_options.py\n" + "\n".join(stale))
        return 1
    print("Report options are in sync.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
